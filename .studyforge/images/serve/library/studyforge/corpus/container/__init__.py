r"""`container.json` — the deepest container's declaration of what its units are.

**What it does.** Reads one container map: its address, the title of each
level, its single variant, when it was ingested, where in the source it came
from, and the unit list with declared practice counts.

**How you use it.** `parse(text, where, manifest)` and `load(path, manifest)`
return a `Container`; `render(container)` gives back the exact bytes, which is
what makes the round trip a guarantee rather than a hope. ⛔ **The manifest is
required**: a container map is meaningless outside its corpus, because its
address must have the corpus's depth and its variant must be one the corpus
declares.

**Depends on.** `studyforge.address`, `studyforge.corpus.manifest`,
`studyforge.archive.scrub` for R7's gate and `studyforge.version` for R9's.
⛔ **This package builds the reader and the round-trip guarantee. It builds no
writer** — nothing here touches disk except `load`, and nothing writes.

## Who writes this, and what a person may amend

⛔ **Generated by the adapter on ingest** (§6), amended only by the declared
practice counts. The render pipeline never writes it, and nobody writes one
from nothing.

⭐ **"Hand-authorable" is about two fields, not about the document.** What a
person may amend are the **editorial** fields — a corrected `title`, an
explanatory `note` — and a generator that would discard one **stops** (R6).
That is not a hole in a skill: R19 forbids a second source having to *retype*
what a skill could have produced, and a judgement about one's own material is
the one thing no skill can produce. ⛔ Everything derivable — the address, the
titles, the variant, the unit list — is generated, and hand-writing it is a
finding against the adapter-authoring skill.

`render` exists for exactly that round trip: read, amend, write back, and the
bytes of everything untouched are the bytes that were there.

## One variant per container

⚠️ A map promising a variant the archive does not hold would be an ambiguous
half-state, and a single-variant container cannot express it.

## `origin` is provenance, and it lives **here** and not in the archive

⭐ **Ruled.** `origin` says where in the
source a container and each of its units came from. It is in the container map
and ⛔ **not** in the archive document, because two places to look for one fact
disagree with each other — and the archive document already
carries what it needs to stand alone, which is its *identity* (R4), not its
provenance.

⚠️ **It is optional, and that is measured rather than generous.** The
extraction source's equivalent field — `folder` — is present in **116 of 285**
maps. A required `origin` would refuse the other 169 and a migration of them
with it.

⛔ **`folder` is `origin`, and it is not `address`.** Of the 116 that carry
one, **none is derivable from the titles**. They are truncated and
carry disambiguating suffixes — `…-and-beyond-in-kotlin` where slugifying the
title gives `…-and-beyond`, and `…-usage-1` where it gives `…-usage`. A site's
own URL scheme is not a function of its titles, which is the same reason a
page's name may not be taken from a source filename. So `folder` has a home
here, and the field it needed already existed.

⛔ **A placement profile that needs it must say so and fail loudly when it is
absent**. `sibling` does: one designed shape's directories are flat while
its address is two levels, so the directory comes from `origin` and the
address is *only* identity — a profile using the address for both would create
new directories beside the material, which is what R3 forbids.

## ⭐ An `origin` may name a **region** of a file — `container_api: 2`

⛔ **Ruled on a real corpus.** A fourth container holds **17** units
that are regions of one file. `origin` named a whole file, so all seventeen
declared the same one and `check_completeness` compared each of them against
that file's **361** headings — ⚠️ *sixteen false short reads, or a check
somebody switches off.*

```json
{
  "n": 3,
  "title": "Card issuance",
  "origin": { "path": "TestCases.md", "section": "3. Card issuance" }
}
```

- `origin` stays a **string** for a whole file. ⛔ Unchanged; every v1 map
  parses exactly as it did.
- It **may be an object** — `path` + `section`, both required. `section` is the
  **exact text** of the ATX heading the region opens with.
- The region **ends** at the next heading of the **same or shallower** depth.
  ⛔ Not at the next heading of any depth: a unit's own subsections are its.
- `section` must occur **exactly once** in the file. ⚠️ Enforced where the file
  is read — `validate.source`, under two rule ids of its own.
- ⛔ **`TestCases.md#…` stops being accepted.** ⭐ It validated and meant
  nothing; `studyforge.sourcepath` refuses a fragment now.

⛔ **A heading, and not a line range or an anchor — the reason is the only
thing that makes the check possible.** `check_completeness` exists to
**disagree** with the Markdown reader, so the region's bound may not come from
it: an anchor is a renderer's slug rule and would. ⭐ `validate.headings`'
own regex already knows a heading's depth, so it finds the opening heading and
the next at that depth or shallower with no parser at all. ⚠️ A line range is
parser-independent too, and was refused for a different reason: it is brittle
against an upstream file that grows a paragraph, and these corpora are living
repositories.

⚠️ **The reader hands back a path and a section separately** — `Unit.origin` is
still a plain path in both shapes, so `origin_directory`'s `.parent` and every
other consumer that wants a location are untouched.

## ⭐ A unit's PRACTICE may come from a file of its own — `container_api: 3`

⛔ **A practice belongs on the page it practises**, as part of each topic page
and never a separate UI after the chapter, which makes it a `practice`
document of that unit.

⚠️ **The renderer already handles this** — a unit page renders every document
in its directory, practice panel and all. The **accounting** is what needs the
key: `validate.source.completeness` compares a unit's whole heading total
against the one file its `origin` names, so a practice added to a prose unit
would read as a short read, because the practice's prose is not in that
file. ⛔ And
putting it there is refused: R3 forbids rewriting a source file, and
`corpus.manifest.edits` refuses an edit to any file the corpus's own `content`
policy classifies as INCLUDED **however it is declared**, so `permitted_edits`
cannot legalise it either.

```json
{
  "n": 4,
  "title": "Message Type Indicators (MTIs)",
  "practices": 1,
  "origin": "src/4.md",
  "practice_origin": "src/p1.md"
}
```

⭐ **THE PLACEMENT RULE, and it is the whole of it:**

- A practice lives in the unit whose material it practises. ⛔ **Not in a
  container of its own**, which is a reader who finished a chapter and then
  navigated away from it.
- A practice's prose comes from `origin` **when the source file already carries
  it**, and the two documents split that one file between them — the runnable
  fixture's shape, and nothing changes for it.
- ⛔ **Otherwise it comes from a NEW file, named by `practice_origin`.** Purely
  additive, beside the material, so R3 holds with **nothing** in
  `permitted_edits`. ⚠️ An existing source file is never edited to make room
  for a practice; that is the refusal above, not a rule of thumb.
- ⛔ **`practice_origin` holds ALL of the unit's `practice` documents and none
  of its `lesson` documents.** The split is the archive's `kind`, so the
  additive file's headings are the practice's headings and nothing else's.
- ⚠️ **`practice_origin` requires `origin`.** The key means *not the file the
  prose came from*; with no prose file there is no other file, and the one path
  belongs in `origin`, where placement can see it.
- ⛔ **It places nothing.** `origin` is what `placement.profile.origin_directory`
  and the contents tree read, and a practice that changed where its unit's page
  went would move the page a reader is already reading.

⭐ **The check is run twice, never relaxed** (R6): a unit declaring
`practice_origin` is compared
**per origin** — its lessons against `origin`, its practices against `practice_origin` — and
**both buckets exist whether or not a document landed in them**, so a
`practice_origin` no practice document reads is a short read rather than a file
nobody counted.

## `label` is presentation carried as data

⚠️ **Optional, per unit, and never identity.** Real material carries its own
display numbering — `4.4.1` — while a page's *name* must come from identity,
because two of the four designed source shapes differ only in zero-padding
(`src/1.md` against `src/04.md`) and a reader that took the number from the
filename would have to know which corpus it was reading (R1).

⛔ The address is still the address and the ordinals are still contiguous;
`label` changes only what a unit is **called**. Nothing may parse one back
into an ordinal — R4's argument about paths, applied to numbering.

⭐ **In the contract from the start**, deliberately. §4's YAGNI refuses
flexibility *nobody has asked for*; a measured corpus needs this, and placement
built the consumer, and pinned it against §5's worked example. And R9 makes
the alternative expensive in a way that is not symmetric: adding a field later
is a `container_api` bump, and every map written under the old version is
**refused, never migrated** (R9) until its adapter is re-run.
"""

