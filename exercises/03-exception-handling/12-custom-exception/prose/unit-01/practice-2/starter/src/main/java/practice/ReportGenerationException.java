package practice;

public class ReportGenerationException extends Exception {

    public ReportGenerationException() {
        throw new UnsupportedOperationException("write ReportGenerationException()");
    }

    public ReportGenerationException(String message) {
        throw new UnsupportedOperationException("write ReportGenerationException(String)");
    }

    public ReportGenerationException(String message, Throwable cause) {
        throw new UnsupportedOperationException("write ReportGenerationException(String, Throwable)");
    }

    public ReportGenerationException(Throwable cause) {
        throw new UnsupportedOperationException("write ReportGenerationException(Throwable)");
    }
}
